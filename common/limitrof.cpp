void Limitrof::printMatrix() const {
    if (mat_ady.empty()) {
        std::cerr << "Matrix is empty!\n";
        return;
    }

    std::cout << "Adjacency Matrix:\n";
    for (const auto& row : mat_ady) {
        for (int val : row) {
            std::cout << val << " ";
        }
        std::cout << std::endl;
    }
}
